/** Changed lines between two versions of a file (a multiset line diff, good enough for a budget). */
function changedLines(a = "", b = "") {
  const left = a.split("\n"), right = b.split("\n");
  const pool = new Map<string, number>();
  left.forEach(l => pool.set(l, (pool.get(l) ?? 0) + 1));
  let common = 0;
  right.forEach(l => { const n = pool.get(l) ?? 0; if (n > 0) { common++; pool.set(l, n - 1); } });
  return left.length - common + (right.length - common);
}
export function diffStats(w: CodingWorld) {
  let lines = 0, files = 0;
  for (const p of new Set([...Object.keys(w.files), ...Object.keys(w.original)])) {
    if (w.files[p] !== w.original[p]) { files++; lines += changedLines(w.original[p], w.files[p]); }
  }
  return { lines, files };
}
function signatureIntact(w: CodingWorld) { return /export function applyDiscount\(\s*totalPaise\s*,\s*pct\s*\)/.test(w.files["src/checkout/pricing.js"] ?? ""); }
function generatedEdited(w: CodingWorld) { return Object.keys(w.files).some(p => p.startsWith("src/generated/") && w.files[p] !== w.original[p]); }

